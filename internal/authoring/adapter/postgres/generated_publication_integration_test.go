func generatedRetirementRecord(t *testing.T, candidate generatedPublicationCandidate, at time.Time) authoringapp.RetireGeneratedPublicationRecord {
	t.Helper()
	generated := candidate.generated.Request
	request := domain.GeneratedPublicationRetirementRequest{WorkspaceID: generated.WorkspaceID, DocumentID: generated.DocumentID,
		ArticleRevisionID: generated.ArticleRevisionID, PublicationID: candidate.publication.ID, OriginKind: generated.OriginKind,
		OriginID: generated.OriginID, OriginRevisionID: generated.OriginRevisionID, ProjectionHash: generated.ProjectionHash,
		ExpectedDocumentVersion: candidate.result.Document.Version, ExpectedProposalVersion: candidate.proposal.Version}
	hash, err := domain.ComputeGeneratedPublicationRetirementRequestHash(request)
	if err != nil {
		t.Fatal(err)
	}
	return authoringapp.RetireGeneratedPublicationRecord{Request: request, IdempotencyKey: "retire-" + candidate.generated.IdempotencyKey, RequestHash: hash, RetiredAt: at}
}

