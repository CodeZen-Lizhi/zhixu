func TestGeneratedAuthoringPostgreSQLPublicationRetirementAtomic(t *testing.T) {
	fixture := newGeneratedPublicationFixture(t)
	ctx := t.Context()
	first := fixture.candidate(t, 22000)
	if first.publication.Status != domain.PublicationPending || first.proposal.Status != changecontroldomain.StatusReady ||
		first.publication.TargetMode != domain.ProposalTargetCreateOnly || first.proposal.Revision.Content != first.generated.Request.Content ||
		!strings.Contains(first.proposal.Revision.EvidenceSummary, "generated by an AGENT") || first.proposal.Approval != nil {
		t.Fatalf("generated candidate did not create an exact unapproved Proposal: %+v", first.proposal)
	}
	fixture.assertNoFiles(t)
	next := generatedIntegrationSuccessor(t, first.generated, first.result, 22100, fixture.now.Add(4*time.Second))
	nextReservation := generatedReservationRecord(t, next, 22109, fixture.now.Add(5*time.Second))
	err := fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		_, err := fixture.repository.AppendGeneratedRevisionScoped(ctx, scope, next)
		return err
	})
	if !authoringIntegrationError(err, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedPublicationBusy) {
		t.Fatalf("new generation ignored the existing review window: %v", err)
	}
	retirement := generatedRetirementRecord(t, first, fixture.now.Add(3*time.Second))
	for _, test := range []struct {
		name   string
		mutate func(*domain.GeneratedPublicationRetirementRequest)
		kind   foundation.ErrorKind
		code   string
	}{
		{"origin", func(value *domain.GeneratedPublicationRetirementRequest) {
			value.OriginID = authoringIntegrationID(22991)
		}, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedOriginConflict},
		{"projection", func(value *domain.GeneratedPublicationRetirementRequest) {
			value.ProjectionHash = strings.Repeat("f", 64)
		}, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedOriginConflict},
		{"document version", func(value *domain.GeneratedPublicationRetirementRequest) { value.ExpectedDocumentVersion++ }, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedOriginConflict},
		{"proposal version", func(value *domain.GeneratedPublicationRetirementRequest) { value.ExpectedProposalVersion++ }, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedPublicationBusy},
		{"publication", func(value *domain.GeneratedPublicationRetirementRequest) {
			value.PublicationID = authoringIntegrationID(22992)
		}, foundation.ErrorNotFound, authoringapp.ErrorCodeNotFound},
		{"workspace", func(value *domain.GeneratedPublicationRetirementRequest) {
			value.WorkspaceID = fixture.otherWorkspaceID
		}, foundation.ErrorNotFound, authoringapp.ErrorCodeNotFound},
	} {
		t.Run(test.name, func(t *testing.T) {
			changed := retirement
			test.mutate(&changed.Request)
			changed.RequestHash, _ = domain.ComputeGeneratedPublicationRetirementRequestHash(changed.Request)
			err := fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
				_, err := fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, changed, fixture.retirer)
				return err
			})
			if !authoringIntegrationError(err, test.kind, test.code) {
				t.Fatalf("forged retirement was accepted: %v", err)
			}
		})
	}
	// A participant claiming success without retiring the actual Proposal cannot
	// close the Authoring binding: its existing database terminal guard rejects it.
	err = fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		_, err := fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, retirement,
			generatedRetirerFunc(func(context.Context, foundation.TransactionScope, authoringapp.GeneratedProposalRetirement) error {
				return nil
			}))
		return err
	})
	if platformpostgres.SQLState(err) != "23514" {
		t.Fatalf("closed binding accepted a fake terminal Proposal: %v", err)
	}
	rollback := errors.New("new semantic candidate rejected")
	var nextResult authoringapp.GeneratedRevisionResult
	var retired authoringapp.RetireGeneratedPublicationResult
	appendCandidate := func(ctx context.Context, scope foundation.TransactionScope) error {
		var err error
		retired, err = fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, retirement, fixture.retirer)
		if err != nil {
			return err
		}
		nextResult, err = fixture.repository.AppendGeneratedRevisionScoped(ctx, scope, next)
		if err != nil {
			return err
		}
		_, err = fixture.repository.ReservePublicationScoped(ctx, scope, nextReservation)
		return err
	}
	err = fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		if err := appendCandidate(ctx, scope); err != nil {
			return err
		}
		return rollback
	})
	if !errors.Is(err, rollback) {
		t.Fatalf("candidate rollback cause changed: %v", err)
	}
	fixture.assertCandidateState(t, first, changecontroldomain.StatusReady, domain.PublicationPending, 1)
	assertGeneratedCount(t, fixture.database, "core.article_revision", "id", string(next.Request.ArticleRevisionID), 0)
	assertGeneratedCount(t, fixture.database, "authoring.generated_publication_retirement", "publication_id", string(first.publication.ID), 0)
	assertGeneratedCount(t, fixture.database, "authoring.document_publication_reservation", "id", string(nextReservation.ReservationID), 0)

	lostResponse := errors.New("retirement commit response lost")
	if err := (authoringCommitResponseLossUnitOfWork{delegate: fixture.uow, cause: lostResponse}).Within(ctx, foundation.TransactionOptions{}, appendCandidate); !errors.Is(err, lostResponse) {
		t.Fatalf("retirement response loss was hidden: %v", err)
	}
	if retired.Replayed || retired.Publication.Status != domain.PublicationClosed || nextResult.Document.Version != first.result.Document.Version+1 {
		t.Fatalf("retirement did not atomically append the new candidate: retired=%+v next=%+v", retired, nextResult)
	}
	fixture.assertCandidateState(t, first, changecontroldomain.StatusNeedsRevision, domain.PublicationClosed, 2)
	assertGeneratedCount(t, fixture.database, "authoring.generated_publication_retirement", "publication_id", string(first.publication.ID), 1)
	if err := fixture.uow.Within(ctx, foundation.TransactionOptions{}, appendCandidate); err != nil || !retired.Replayed || !nextResult.Replayed {
		t.Fatalf("committed candidate did not exactly recover after response loss: %v", err)
	}
	var replay authoringapp.RetireGeneratedPublicationResult
	err = fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		var err error
		replay, err = fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, retirement,
			generatedRetirerFunc(func(context.Context, foundation.TransactionScope, authoringapp.GeneratedProposalRetirement) error {
				return errors.New("retirement replay invoked Change Control again")
			}))
		return err
	})
	if err != nil || !replay.Replayed || replay.Publication != retired.Publication {
		t.Fatalf("retirement replay changed after the document advanced: %+v error=%v", replay, err)
	}
	if err := fixture.database.Exec(`UPDATE authoring.generated_publication_retirement SET expected_document_version=expected_document_version+1 WHERE publication_id=?`, string(first.publication.ID)).Error; platformpostgres.SQLState(err) != "55000" {
		t.Fatalf("retirement receipt was mutable: %v", err)
	}
	second := generatedPublicationCandidate{generated: next, result: nextResult}
	second.publication = fixture.publish(t, next, fixture.now.Add(6*time.Second))
	second.proposal, err = fixture.proposals.GetProposal(ctx, second.publication.ProposalID)
	if err != nil || second.proposal.Status != changecontroldomain.StatusReady || second.proposal.ID == first.proposal.ID ||
		second.proposal.Revision.Content != next.Request.Content || second.proposal.Approval != nil {
		t.Fatalf("new candidate did not get its own exact Proposal: %+v error=%v", second.proposal, err)
	}
	assertGeneratedCount(t, fixture.database, "core.article_revision", "document_id", string(next.Request.DocumentID), 2)
	assertGeneratedCount(t, fixture.database, "change_control.approval", "proposal_id", string(first.proposal.ID), 0)
	fixture.assertNoFiles(t)
	approval := generatedApproval(second, 22110, fixture.now.Add(7*time.Second))
	if _, err := fixture.proposals.Approve(ctx, approval); err != nil {
		t.Fatal(err)
	}
	second.proposal.Version++
	approvedRetirement := generatedRetirementRecord(t, second, fixture.now.Add(8*time.Second))
	err = fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		_, err := fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, approvedRetirement, fixture.retirer)
		return err
	})
	if !authoringIntegrationError(err, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedPublicationBusy) {
		t.Fatalf("retirement invalidated an actual approval: %v", err)
	}
	fixture.assertCandidateState(t, second, changecontroldomain.StatusApproved, domain.PublicationPending, 2)
	assertGeneratedCount(t, fixture.database, "change_control.approval", "proposal_id", string(second.proposal.ID), 1)
	assertGeneratedCount(t, fixture.database, "authoring.generated_publication_retirement", "publication_id", string(second.publication.ID), 0)
	fixture.assertNoFiles(t)
}

func TestGeneratedAuthoringPostgreSQLRetirementWinsApprovalRace(t *testing.T) {
	fixture := newGeneratedPublicationFixture(t)
	first := fixture.candidate(t, 23000)
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Second)
	defer cancel()
	retirement := generatedRetirementRecord(t, first, fixture.now.Add(3*time.Second))
	approvalDone := make(chan error, 1)
	started := false
	err := fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		if _, err := fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, retirement, fixture.retirer); err != nil {
			return err
		}
		started = true
		go func() {
			_, err := fixture.proposals.Approve(ctx, generatedApproval(first, 23010, fixture.now.Add(4*time.Second)))
			approvalDone <- err
		}()
		return waitGeneratedProposalLock(ctx, fixture.platform, "%change_control.proposal AS proposal%")
	})
	if !started {
		t.Fatalf("retirement did not acquire its candidate locks: %v", err)
	}
	var approvalErr error
	select {
	case approvalErr = <-approvalDone:
	case <-ctx.Done():
		t.Fatalf("approval did not exit after retirement: %v", ctx.Err())
	}
	if err != nil || !authoringIntegrationError(approvalErr, foundation.ErrorVersionConflict, "PROPOSAL_NOT_READY_FOR_REVIEW") {
		t.Fatalf("retirement/approval lock ordering failed: retire=%v approve=%v", err, approvalErr)
	}
	fixture.assertCandidateState(t, first, changecontroldomain.StatusNeedsRevision, domain.PublicationClosed, 2)
	assertGeneratedCount(t, fixture.database, "change_control.approval", "proposal_id", string(first.proposal.ID), 0)
}

func TestGeneratedAuthoringPostgreSQLApprovalWinsRetirementRace(t *testing.T) {
	fixture := newGeneratedPublicationFixture(t)
	first := fixture.candidate(t, 24000)
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Second)
	defer cancel()
	events, err := eventspostgres.NewGORMStore(fixture.platform)
	if err != nil {
		t.Fatal(err)
	}
	gate := generatedApprovalEventGate{delegate: events, entered: make(chan struct{}), release: make(chan struct{})}
	proposals, err := changecontrolpostgres.NewGORMRepository(fixture.platform, gate)
	if err != nil {
		t.Fatal(err)
	}
	approvalDone := make(chan error, 1)
	go func() {
		_, err := proposals.Approve(ctx, generatedApproval(first, 24010, fixture.now.Add(3*time.Second)))
		approvalDone <- err
	}()
	select {
	case <-gate.entered:
	case err := <-approvalDone:
		t.Fatalf("approval did not reach the precommit event barrier: %v", err)
	case <-ctx.Done():
		t.Fatal(ctx.Err())
	}
	retirement := generatedRetirementRecord(t, first, fixture.now.Add(4*time.Second))
	retirementDone := make(chan error, 1)
	go func() {
		retirementDone <- fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
			_, err := fixture.repository.RetireGeneratedPublicationScoped(ctx, scope, retirement, fixture.retirer)
			return err
		})
	}()
	lockErr := waitGeneratedProposalLock(ctx, fixture.platform, "%FOR UPDATE OF p,r%")
	close(gate.release)
	var approvalErr, retirementErr error
	select {
	case approvalErr = <-approvalDone:
	case <-ctx.Done():
		t.Fatal(ctx.Err())
	}
	select {
	case retirementErr = <-retirementDone:
	case <-ctx.Done():
		t.Fatal(ctx.Err())
	}
	if lockErr != nil || approvalErr != nil || !authoringIntegrationError(retirementErr, foundation.ErrorVersionConflict, domain.ErrorCodeGeneratedPublicationBusy) {
		t.Fatalf("approval/retirement lock ordering failed: wait=%v approve=%v retire=%v", lockErr, approvalErr, retirementErr)
	}
	fixture.assertCandidateState(t, first, changecontroldomain.StatusApproved, domain.PublicationPending, 2)
	assertGeneratedCount(t, fixture.database, "change_control.approval", "proposal_id", string(first.proposal.ID), 1)
	assertGeneratedCount(t, fixture.database, "authoring.generated_publication_retirement", "publication_id", string(first.publication.ID), 0)
}

