func TestGeneratedAuthoringPostgreSQLPublishedBaselineAndHistoricalReplay(t *testing.T) {
	fixture := newGeneratedPublicationFixture(t)
	ctx := t.Context()
	if err := fixture.platform.DB().QueryRow(ctx, `SELECT CURRENT_TIMESTAMP - INTERVAL '1 minute'`).Scan(&fixture.now); err != nil {
		t.Fatal(err)
	}
	first := fixture.candidate(t, 26000)
	reservation, found, err := gormLoadReservation(ctx, fixture.database, fixture.workspaceID, first.publication.ReservationID, false)
	if err != nil || !found {
		t.Fatalf("candidate reservation was not persisted: %v", err)
	}
	// Existing owner fixture writes the full Approval/Authorization/execution/
	// proposal_commit chain. Git and filesystem execution remain composition tests.
	gitCommit := seedAuthoringProposalCommit(t, ctx, fixture.platform, first.proposal, reservation,
		first.generated.Request.Content, 26100, fixture.now.Add(3*time.Second))
	advanced, err := fixture.repository.ReconcilePublications(ctx, authoringapp.ReconcileQuery{
		WorkspaceID: fixture.workspaceID, DocumentID: first.result.Document.ID, Limit: 1, Now: fixture.now.Add(4 * time.Second),
	})
	if err != nil || advanced != 1 {
		t.Fatalf("generated publication did not finalize from its exact commit: advanced=%d error=%v", advanced, err)
	}
	detail, err := fixture.repository.GetDocumentDetail(ctx, fixture.workspaceID, first.result.Document.ID)
	if err != nil || detail.Document.Lifecycle != domain.DocumentPublished || detail.Document.CurrentPublishedRevisionID != first.result.Revision.ID ||
		detail.CurrentRevision == nil || detail.CurrentRevision.Status != domain.RevisionPublished || detail.CurrentRevision.GitCommit != gitCommit ||
		detail.CurrentRevision.CreatedByType != "AGENT" || detail.CurrentRevision.SourceVersionID != "" {
		t.Fatalf("generated publication lost its identity or owner pointer: %+v error=%v", detail, err)
	}
	replay := fixture.append(t, first.generated)
	if !replay.Replayed || replay.Document != first.result.Document || replay.Revision != first.result.Revision {
		t.Fatalf("publishing changed the original generation receipt: %+v", replay)
	}
	next := generatedIntegrationSuccessor(t, first.generated,
		authoringapp.GeneratedRevisionResult{Document: detail.Document, Revision: *detail.CurrentRevision}, 26200, fixture.now.Add(5*time.Second))
	nextReservation := generatedReservationRecord(t, next, 26209, fixture.now.Add(6*time.Second))
	var appended authoringapp.GeneratedRevisionResult
	var prepared authoringapp.PublicationPreparation
	err = fixture.uow.Within(ctx, foundation.TransactionOptions{}, func(ctx context.Context, scope foundation.TransactionScope) error {
		var err error
		appended, err = fixture.repository.AppendGeneratedRevisionScoped(ctx, scope, next)
		if err != nil {
			return err
		}
		prepared, err = fixture.repository.ReservePublicationScoped(ctx, scope, nextReservation)
		return err
	})
	if err != nil || appended.Document.CurrentPublishedRevisionID != first.result.Revision.ID || appended.Document.Lifecycle != domain.DocumentPublished ||
		appended.Document.Version != detail.Document.Version+1 || appended.Revision.Status != domain.RevisionDraft ||
		prepared.Reservation.TargetMode != domain.ProposalTargetReplace || prepared.Reservation.BaseVersion != first.result.Revision.ContentHash {
		t.Fatalf("next candidate changed the published baseline: appended=%+v prepared=%+v error=%v", appended, prepared, err)
	}
	// Represent the already-written file for the real read-only Proposal reader.
	path := filepath.Join(fixture.rootPath, first.generated.Request.TargetPath)
	if err := os.WriteFile(path, []byte(first.generated.Request.Content), 0o600); err != nil {
		t.Fatal(err)
	}
	publication := fixture.publish(t, next, fixture.now.Add(7*time.Second))
	if publication.TargetMode != domain.ProposalTargetReplace || publication.Status != domain.PublicationPending {
		t.Fatalf("successor did not create a governed replacement: %+v", publication)
	}
	content, err := os.ReadFile(path)
	if err != nil || string(content) != first.generated.Request.Content {
		t.Fatalf("unapproved replacement changed the current file: %v", err)
	}
}

