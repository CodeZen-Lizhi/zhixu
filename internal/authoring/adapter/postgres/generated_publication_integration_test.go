func waitGeneratedProposalLock(ctx context.Context, pool *platformpostgres.Pool, queryPattern string) error {
	waitCtx, cancel := context.WithTimeout(ctx, 3*time.Second)
	defer cancel()
	ticker := time.NewTicker(10 * time.Millisecond)
	defer ticker.Stop()
	for {
		var waiting bool
		if err := pool.DB().QueryRow(waitCtx, `SELECT EXISTS (
			SELECT 1 FROM pg_stat_activity WHERE datname=current_database() AND pid<>pg_backend_pid()
			AND state='active' AND wait_event_type='Lock' AND query LIKE $1
		)`, queryPattern).Scan(&waiting); err != nil {
			return err
		}
		if waiting {
			return nil
		}
		select {
		case <-ticker.C:
		case <-waitCtx.Done():
			return fmt.Errorf("concurrent candidate command never waited on its Proposal lock: %w", waitCtx.Err())
		}
	}
}

