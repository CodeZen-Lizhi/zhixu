// The real event append occurs inside Approve's transaction. The barrier holds
// that transaction immediately before commit so the competing retirement must wait.
type generatedApprovalEventGate struct {
	delegate eventsapp.ScopedAppender
	entered  chan struct{}
	release  chan struct{}
}

func (gate generatedApprovalEventGate) AppendScoped(ctx context.Context, scope foundation.TransactionScope, request eventsdomain.AppendRequest) (eventsdomain.ServerEvent, bool, error) {
	event, replayed, err := gate.delegate.AppendScoped(ctx, scope, request)
	if err != nil {
		return event, replayed, err
	}
	close(gate.entered)
	select {
	case <-gate.release:
		return event, replayed, nil
	case <-ctx.Done():
		return eventsdomain.ServerEvent{}, false, ctx.Err()
	}
}
